"""Regenerate the checked-in Q15 response tables; normal builds need no Python."""
from pathlib import Path
import math

destination=Path(__file__).resolve().parents[1]/'lib/controller_bridge/analog_curves.h'
# Keep the earlier 1.2/1.6 responses for existing saved profiles.
powers=(0.4,0.6,0.8,1.2,1.4,1.6,2.0,3.0)
lines=['// Generated by tools/generate-analog-curves.py. Q15 values at x = i/256.',
       '// The runtime applies the preview\'s finite 4x gain cap after interpolation.',
       '#ifndef CONTROLLER_ANALOG_CURVES_H','#define CONTROLLER_ANALOG_CURVES_H',
       f'static const uint16_t analog_curves[{len(powers)}][257] = {{']
for power in powers:
 values=[math.floor((i/256)**power*32768+0.5) for i in range(257)]
 lines.append(f'    {{ // gamma {power:.1f}')
 for start in range(0,len(values),16):lines.append('        '+','.join(map(str,values[start:start+16]))+',')
 lines.append('    },')
lines+=['};','#endif','']
destination.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
