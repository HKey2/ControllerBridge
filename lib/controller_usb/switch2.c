bool uc_switch2_config(const uint8_t *data,size_t length,uint8_t bulk[2][7]) {
    memset(bulk,0,14);bool selected=false;
    for(size_t at=0;at<length;) {
        const uint8_t *d=data+at;
        if(length-at<2 || d[0]<2 || d[0]>length-at)return false;
        if(d[1]==4) {
            if(d[0]<9)return false;
            selected=d[2]==1 && d[3]==0 && d[5]==0xff;
        } else if(selected && d[1]==5) {
            if(d[0]<7)return false;
            if((d[3]&3)==2) {
                unsigned i=(d[2]&0x80)?1:0;
                if(bulk[i][0] || d[2]!=(i?0x82:2) || d[4]!=64 || d[5])return false;
                memcpy(bulk[i],d,7);
            }
        }
        at+=d[0];
    }
    return bulk[0][0] && bulk[1][0];
}
